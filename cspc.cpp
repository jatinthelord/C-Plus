static std::string read_file(const fs::path &path) {
  std::ifstream input(path, std::ios::binary);
  if (!input)
    throw std::runtime_error("cannot open source file: " + path.string());
  return {std::istreambuf_iterator<char>(input),
          std::istreambuf_iterator<char>()};
}

static void write_file(const fs::path &path, const std::string &data) {
  std::ofstream output(path, std::ios::binary);
  if (!output)
    throw std::runtime_error("cannot write file: " + path.string());
  output << data;
}

static bool build_input_newer_than(const fs::path &root,
                                   fs::file_time_type output_time) {
  std::error_code error;
  if (!fs::exists(root, error))
    return false;
  if (fs::is_regular_file(root, error))
    return fs::last_write_time(root, error) > output_time;
  fs::recursive_directory_iterator entries(
      root, fs::directory_options::skip_permission_denied, error);
  for (const auto &entry : entries) {
    if (error) {
      error.clear();
      continue;
    }
    if (!entry.is_regular_file(error))
      continue;
    const std::string extension = entry.path().extension().string();
    if (extension != ".h" && extension != ".hh" && extension != ".hpp" &&
        extension != ".hxx" && extension != ".inc" && !extension.empty())
      continue;
    if (entry.last_write_time(error) > output_time)
      return true;
  }
  return false;
}

static std::string transpile(std::string source, const fs::path &filename,
                             bool include_runtime) {
  std::string display = filename.generic_string();
  const bool uses_optional = source.find("std::optional") != std::string::npos;
  return "// Generated by C+ " + std::string(VERSION) + "\n" +
         (uses_optional ? std::string("#include <optional>\n") : std::string()) +
         (include_runtime ? std::string(RUNTIME) : std::string()) +
         "\n#line 1 \"" + display + "\"\n" + source + "\n";
}

static std::string quote(const fs::path &value) {
  std::string text = value.string();
  std::string escaped = "\"";
  for (char c : text)
    escaped += (c == '"' ? "\\\"" : std::string(1, c));
  return escaped + "\"";
}

